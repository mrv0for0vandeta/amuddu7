// ─── Deterministic image picker ──────────────────────────────────
function hashId(id: string): number {
  let h = 0;
  for (let i = 0; i < id.length; i++) {
    h = ((h << 5) - h + id.charCodeAt(i)) | 0;
  }
  return Math.abs(h);
}

function pickImage(pool: ImgId[], id: string): string | null {
  if (!pool || pool.length === 0) return null;
  const idx = hashId(id) % pool.length;
  const imgId = pool[idx];
  if (!imgId) return null;
  return px(imgId, pngIds.has(imgId));
}

// ─── Public API ──────────────────────────────────────────────────

export function getListingImage(
  listingId: string,
  visualType: string | null,
  category: string,
  title: string,
  regionId?: string,
): string {
  // Primary: visual_type pool
  if (visualType) {
    const pool = pools[visualType];
    const img = pool ? pickImage(pool, listingId) : null;
    if (img) return img;
  }

  // Secondary: category fallback pool
  const fallbackVt = categoryFallbacks[category];
  if (fallbackVt) {
    const pool = pools[fallbackVt];
    const img = pool ? pickImage(pool, listingId) : null;
    if (img) return img;
  }

  // Tertiary: city hero image
  if (regionId && heroImages[regionId]) {
    return px(heroImages[regionId], pngIds.has(heroImages[regionId]));
  }

  return px(fallbackHero);
}

export function getHeroImage(regionId: string): string {
  const id = heroImages[regionId] ?? fallbackHero;
  return px(id, pngIds.has(id));
}

export function getCategoryIcon(category: string, title?: string): LucideIcon {
  if (category === 'transfer' && title) {
    const t = title.toLowerCase();
    if (/train|oncf|rail|station/.test(t)) return TrainFront;
    if (/shuttle|shared|bus|minibus/.test(t)) return Car;
    return Car;
  }
  if (category === 'activity' && title) {
    const t = title.toLowerCase();
    if (/surf|kite|wind|wave|beach|ocean|sail|kayak|paddle|water/.test(t)) return Waves;
    if (/bike|cycl/.test(t)) return Bike;
    if (/photo|camera/.test(t)) return Camera;
    return Mountain;
  }
  return categoryIcons[category] ?? Compass;
}
